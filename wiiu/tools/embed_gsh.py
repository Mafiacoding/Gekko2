#!/usr/bin/env python3
# GPL-3.0-or-later. Turns an assembled present.gsh (latte-assembler output) into app/present_gsh_embedded.h so the
# app shows its picture through GX2 without a file on the SD card. Usage: tools/embed_gsh.py path/to/present.gsh
import sys, pathlib
data = pathlib.Path(sys.argv[1]).read_bytes()
if data[:4] != b'Gfx2':
    sys.exit('not a GFD file (expected magic Gfx2)')
out = pathlib.Path(__file__).resolve().parents[1] / 'app' / 'present_gsh_embedded.h'
lines = ['/* Generated by tools/embed_gsh.py from %s (%d bytes). */' % (pathlib.Path(sys.argv[1]).name, len(data)),
         'static const unsigned char present_gsh_data[%d] __attribute__((aligned(256))) = {' % len(data)]
for i in range(0, len(data), 16):
    lines.append('    ' + ', '.join('0x%02x' % b for b in data[i:i + 16]) + ',')
lines.append('};')
out.write_text('\n'.join(lines) + '\n')
print('wrote', out)
