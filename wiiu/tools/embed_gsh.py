#!/usr/bin/env python3
# GPL-3.0-or-later. Turns an assembled .gsh (latte-assembler output) into a C header with a byte array.
# Default (one argument): app/present_gsh_embedded.h with present_gsh_data, so the app shows its picture through
# GX2 without a file on the SD card.
# Usage: tools/embed_gsh.py path/to/present.gsh
#        tools/embed_gsh.py path/to/x.gsh --name gs_color_gsh_data --out gx2/src/gs_color_gsh.h
import sys, pathlib
args = sys.argv[1:]
if not args:
    sys.exit(__doc__ or 'usage: embed_gsh.py file.gsh [--name NAME] [--out PATH]')
src = pathlib.Path(args[0])
name, out = 'present_gsh_data', pathlib.Path(__file__).resolve().parents[1] / 'app' / 'present_gsh_embedded.h'
i = 1
while i < len(args):
    if args[i] == '--name' and i + 1 < len(args):
        name = args[i + 1]; i += 2
    elif args[i] == '--out' and i + 1 < len(args):
        out = pathlib.Path(args[i + 1]); i += 2
    else:
        sys.exit('unknown argument: ' + args[i])
data = src.read_bytes()
if data[:4] != b'Gfx2':
    sys.exit('not a GFD file (expected magic Gfx2)')
lines = ['/* Generated by tools/embed_gsh.py from %s (%d bytes). */' % (src.name, len(data)),
         'static const unsigned char %s[%d] __attribute__((aligned(256))) = {' % (name, len(data))]
for j in range(0, len(data), 16):
    lines.append('    ' + ', '.join('0x%02x' % b for b in data[j:j + 16]) + ',')
lines.append('};')
out.write_text('\n'.join(lines) + '\n')
print('wrote', out)
